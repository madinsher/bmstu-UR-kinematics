"""Вариант ДЗ1 по номеру группы g и номеру в списке n:  python variant.py 73 12"""
import sys

T1 = {1: (1.0, 0.8, 1.6), 2: (1.2, 1.0, 1.8), 3: (1.4, 1.2, 1.6), 4: (1.6, 1.4, 1.8), 5: (0.8, 0.6, 1.4),
      6: (0.7, 0.7, 1.3), 7: (1.0, 0.8, 1.6), 8: (1.5, 1.3, 2.2), 9: (1.2, 1.4, 2.5)}
T2 = {1: (0.5, 0.4, 0.3), 2: (0.4, 0.3, 0.1), 3: (-0.4, 0.4, -0.6), 4: (0.5, -0.4, 0.3), 5: (0.6, -1.0, 0.5), 6: (0.3, 0.3, 0.3)}
T3 = {1: (0.0, 0.5, 0.1), 2: (-0.1, 0.5, 0.0), 3: (0.4, 0.3, 0.1)}
NAMES = {1: 'схема 1 (ВПП)', 2: 'схема 2 (ВПВ)', 3: 'схема 3 (ВВП)'}


def variant(g, n):
    return ((g + n) % 3) + 1, ((g + n) // 4) % 9 + 1, (n % 6) + 1, (n % 3) + 1


if __name__ == '__main__':
    if len(sys.argv) != 3:
        print(__doc__); sys.exit(1)
    g, n = int(sys.argv[1]), int(sys.argv[2])
    sc, t1, t2, t3 = variant(g, n)
    print('группа %d, номер %d' % (g, n))
    print('кинематическая схема: %s' % NAMES[sc])
    print('табл. 1, вариант %d: l1 = %.1f, l2 = %.1f, l3 = %.1f м' % ((t1,) + T1[t1]))
    print('табл. 2, вариант %d: X = %.1f, Y = %.1f, Z = %.1f м' % ((t2,) + T2[t2]))
    print('табл. 3, вариант %d: Vx = %.1f, Vy = %.1f, Vz = %.1f м/с' % ((t3,) + T3[t3]))
